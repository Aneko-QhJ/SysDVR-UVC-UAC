#!/usr/bin/env python3
"""Build the U2 base payload: 18 descriptor edits + 8 alt0-filter NOPs.

This is the prerequisite for the UAC alt1 endpoint install.  It does not
include the ISO producer; posting data still needs the A23-style producer port
to EP 0x84 (documented separately).  Validates every before word against the
usb ELF; no USB/SD/hardware access.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path

from build_uac_descriptor_payload import EDITS as DESCRIPTOR_EDITS
from build_uac_descriptor_payload import (
    USB_BUILD_ID,
    USB_ELF_SHA256,
    USB_ELF_SIZE,
    load_elf_sections,
    validate,
)

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ELF = ROOT / "private/module/usb.elf"
DEFAULT_OUT = ROOT / "private/analysis/UAC-u2-base-20261030/uac_u2_base_payload.h"
DEFAULT_MANIFEST = ROOT / "private/analysis/UAC-u2-base-20261030/manifest.json"

NOP_EDITS = [
    (0x29694, 0x35FFFF09, 0xD503201F),
    (0x29AD4, 0x35FFFF09, 0xD503201F),
    (0x29BA4, 0x35FFFF09, 0xD503201F),
    (0x29C88, 0x35FFFF09, 0xD503201F),
    (0x29D54, 0x35FFFF09, 0xD503201F),
    (0x29E38, 0x35FFFF09, 0xD503201F),
    (0x29F04, 0x35FFFF09, 0xD503201F),
    (0x29FE8, 0x35FFFF09, 0xD503201F),
]
EDITS = DESCRIPTOR_EDITS + NOP_EDITS


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def validate_all(data, sections):
    validate(data, sections)
    if len(data) != USB_ELF_SIZE or sha256(data) != USB_ELF_SHA256:
        raise ValueError("usb ELF identity mismatch")
    for address, before, after in NOP_EDITS:
        start = None
        for sec in sections.values():
            if sec["type"] != 8 and sec["addr"] <= address < sec["addr"] + sec["size"]:
                start = sec["offset"] + address - sec["addr"]
                break
        if start is None:
            raise ValueError(f"{address:#x} outside mapped sections")
        actual = struct.unpack_from("<I", data, start)[0]
        if actual != before:
            raise ValueError(f"{address:#x}: expected {before:#08x}, found {actual:#08x}")


def render():
    lines = [
        "/* Generated by tools/build_uac_u2_base_payload.py; not tracked. */",
        "static const unsigned char uacU2BaseBuildId[32]={"
        + ",".join(str(b) for b in USB_BUILD_ID)
        + "};",
    ]
    for i, (address, before, after) in enumerate(EDITS):
        lines.append(
            f"static const unsigned char uacU2Base_{i}_before[]={{"
            + ",".join(str(b) for b in struct.pack("<I", before))
            + "};"
        )
        lines.append(
            f"static const unsigned char uacU2Base_{i}_after[]={{"
            + ",".join(str(b) for b in struct.pack("<I", after))
            + "};"
        )
    records = [
        f"{{0x{address:x},4,uacU2Base_{i}_before,uacU2Base_{i}_after}}"
        for i, (address, _b, _a) in enumerate(EDITS)
    ]
    lines.append("static const IsoRuntimeEdit uacU2BaseEdits[]={" + ",".join(records) + "};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--elf", type=Path, default=DEFAULT_ELF)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    data = args.elf.read_bytes()
    _raw, sections = load_elf_sections(args.elf)
    validate_all(data, sections)
    header = render()
    doc = {
        "schema": "UAC-u2-base-payload-1",
        "elf": str(args.elf),
        "elf_sha256": USB_ELF_SHA256,
        "build_id": USB_BUILD_ID.hex().upper(),
        "descriptor_edits": len(DESCRIPTOR_EDITS),
        "nop_edits": len(NOP_EDITS),
        "edit_count": len(EDITS),
        "includes_producer": False,
        "header_sha256": sha256(header.encode()),
    }
    if args.check:
        if args.out.read_text() != header:
            raise SystemExit("header differs")
        if json.loads(args.manifest.read_text()) != doc:
            raise SystemExit("manifest differs")
        print(f"ok: {len(EDITS)} edits")
        return
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header)
    args.manifest.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {args.out} ({len(DESCRIPTOR_EDITS)} descriptor + {len(NOP_EDITS)} NOP)")


if __name__ == "__main__":
    main()
