#!/usr/bin/env python3
"""Build an offline A23 URB-field trace (v4) sysmodule.

The v4 report payload writes the consumer index and the last completed URB
entry's ``+0x10`` (IOVA) and ``+0x20`` (requested size) into diagnostics.
A zero size is the ``FUN_0002c690`` unmap skip; a zero/stale IOVA is the
``FUN_00004c70`` miss.  The payload is assembled at the frozen 684-byte RX
cave; the IPS and the runtime-payload header are generated from the same
manifest so the sysmodule and the patch cannot drift.

No USB, SD, package installation, or hardware access.
"""
import argparse
import hashlib
import json
import shutil
import subprocess
from pathlib import Path

from build_patch import BUILD_ID, SHA256, build, ips32, read_mapped, validate_module

ROOT = Path(__file__).resolve().parents[1]
REPO = ROOT.parents[1]
SAFE_STREAM_COMMIT = "77e7480"
TOOLCHAIN = Path("/opt/devkitpro/devkitA64/bin")
MAKE_SOURCES = "source source/sysmodule source/uvc"


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def git_show(spec, path):
    return subprocess.check_output(["git", "-C", str(REPO), "show", f"{spec}:{path}"])


def runtime_header(manifest, path):
    lines = [
        "/* Generated by tools/build_a23_urb_trace.py; not tracked. */",
        "static const unsigned char isoRuntimeBuildId[32]={"
        + ",".join(str(b) for b in bytes.fromhex(manifest["build_id"])) + "};",
    ]
    records = []
    for i, edit in enumerate(manifest["edits"]):
        before = bytes.fromhex(edit["before"])
        after = bytes.fromhex(edit["after"])
        for label, data in (("before", before), ("after", after)):
            lines.append(
                f"static const unsigned char isoRuntime_{i}_{label}[]={{"
                + ",".join(str(b) for b in data) + "};"
            )
        records.append(
            f"{{0x{int(edit['address'], 16):x},{len(before)},"
            f"isoRuntime_{i}_before,isoRuntime_{i}_after}}"
        )
    lines.append("static const IsoRuntimeEdit isoRuntimeEdits[]={" + ",".join(records) + "};")
    path.write_text("\n".join(lines) + "\n")


def stream_stub_header(payload, path):
    """No-op START delta: before == after == the post-boot payload word."""
    word = payload[:4]
    lines = [
        "/* Generated no-op START delta; the v4 trace is a boot-time patch. */",
        "static const unsigned char isoRuntimeStreamSame[4]={"
        + ",".join(str(b) for b in word) + "};",
        "static const IsoRuntimeEdit isoRuntimeStreamEdits[]={{0x68d54,4,"
        "isoRuntimeStreamSame,isoRuntimeStreamSame}};",
    ]
    path.write_text("\n".join(lines) + "\n")


def prepare_source(dest, header, stream_header):
    src = dest / "source"
    shutil.copytree(REPO / "source", src)
    # Safe 77e7480 stream source, not the current working-tree experiment.
    (src / "uvc/uvc_device.c").write_bytes(git_show(SAFE_STREAM_COMMIT, "source/uvc/uvc_device.c"))
    source = (src / "uvc/uvc_device.c").read_text()
    if "#define ISO_STREAM_BUFFERS 3" not in source:
        raise ValueError("safe stream source lost its 3-buffer default")
    source = source.replace("#define ISO_STREAM_BUFFERS 3", "#define ISO_STREAM_BUFFERS 640")
    old_magic = """        if (diag.magic == ISO_PROBE_DIAG_MAGIC || isoProbeIsBurstDiagnostics(diag.magic) || diag.magic == ISO_PROBE_REPORT_MARKER ||"""
    new_magic = """        if (diag.magic == ISO_PROBE_DIAG_MAGIC || isoProbeIsBurstDiagnostics(diag.magic) ||
            diag.magic == ISO_PROBE_URB_TRACE_MAGIC ||
            diag.magic == ISO_PROBE_URB_ENTRIES_MAGIC || diag.magic == ISO_PROBE_REPORT_MARKER ||"""
    if old_magic not in source:
        raise ValueError("safe stream diagnostics gate missing")
    source = source.replace(old_magic, new_magic, 1)
    old = """        if (now >= next) {
            for (u32 b = 0; b < ISO_STREAM_BUFFERS; ++b) {"""
    new = """        if (now >= next && g_isoStreamPosts == g_isoStreamCompletes) {
            for (u32 b = 0; b < ISO_STREAM_BUFFERS; ++b) {"""
    if old not in source:
        raise ValueError("one-in-flight insertion point missing")
    source = source.replace(old, new, 1)
    (src / "uvc/uvc_device.c").write_text(source)
    # The v4 magic must be recognized by this sysmodule's _pollIsoProbe.
    shutil.copyfile(REPO / "source/uvc/iso_probe_protocol.h", src / "uvc/iso_probe_protocol.h")
    shutil.copyfile(header, src / "uvc/iso_runtime_payload.h")
    shutil.copyfile(stream_header, src / "uvc/iso_runtime_stream_payload.h")


def build_nsp(work, source_root, output_dir):
    build_obj = work / "objects"
    output_dir.mkdir(parents=True, exist_ok=True)
    cmd = [
        "make", "-B", "-j4",
        "TARGET=exefs",
        "BUILD=" + build_obj.relative_to(REPO).as_posix(),
        "OUTPUT_DIR=" + output_dir.relative_to(REPO).as_posix(),
        "SOURCES=" + " ".join(
            (source_root / part).relative_to(REPO).as_posix() for part in MAKE_SOURCES.split()
        ),
        "INCLUDES=include",
        "DEFINES=-DISO_PROBE -DISO_PROBE_STREAM -DISO_RUNTIME_PATCH -DFILE_LOGGING "
        "-DISO_PROBE_ALT1 -DISO_PROBE_MPS=256 -DISO_PROBE_INTERVAL=4",
    ]
    with (work / "build.log").open("w") as log:
        subprocess.run(cmd, cwd=REPO, stdout=log, stderr=subprocess.STDOUT, check=True)
    return output_dir / "exefs.nsp"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True, help="new analysis directory")
    parser.add_argument("--nso", type=Path, default=ROOT / "private/module/exefs/main")
    parser.add_argument("--toolchain", type=Path, default=TOOLCHAIN)
    parser.add_argument("--skip-nsp", action="store_true", help="build payload/IPS only")
    parser.add_argument("--layout", choices=("last", "entries"), default="last",
                        help="v4 last completed URB (default) or v5 all 8 entries")
    args = parser.parse_args()
    out = args.output.resolve()
    if out.exists():
        raise SystemExit(f"refusing to overwrite {out}")
    out.mkdir(parents=True)
    patch_dir = out / "patch"
    patch_dir.mkdir()
    nso = validate_module(args.nso.read_bytes())
    layout = {
        "last": {
            "asm": ROOT / "patches/iso_burst_urb_trace.S",
            "schema": "A23-URB-trace-v4-1",
            "trace_layout": "urb-v4",
            "magic": "ISO8",
            "fields": {"consumer": 8, "last_iova": 12, "last_size": 16},
        },
        "entries": {
            "asm": ROOT / "patches/iso_burst_urb_entries.S",
            "schema": "A23-URB-entries-v5-1",
            "trace_layout": "urb-v5",
            "magic": "ISO9",
            "fields": {"entries": 8, "stride": 8, "count": 8, "entry_iova": 0, "entry_size": 4},
        },
    }[args.layout]
    asm = layout["asm"]

    # build() validates the module, assembles the override at 0x68d54,
    # writes the cave/branch/descriptor IPS and its manifest.
    build(
        nso, 1, args.toolchain, patch_dir, frame_lead=32, explicit_all=True,
        mps=256, burst=True, interval=4, assembly_override=asm,
    )
    manifest = json.loads((patch_dir / "manifest.json").read_text())
    cave_edit = next(e for e in manifest["edits"] if int(e["address"], 16) == 0x68D54)
    payload = bytes.fromhex(cave_edit["after"])
    if len(payload) > 684:
        raise ValueError(f"payload {len(payload)} exceeds the 684-byte cave")
    # The A23 alt1 endpoint needs the eight FUN_000295d0 alt0-filter NOPs.
    nop_before = bytes.fromhex("09ffff35")
    nop_after = bytes.fromhex("1f2003d5")
    for address in (0x29694, 0x29AD4, 0x29BA4, 0x29C88, 0x29D54, 0x29E38, 0x29F04, 0x29FE8):
        if read_mapped(nso, address, len(nop_before)) != nop_before:
            raise ValueError(f"alt1 NOP original mismatch at {address:#x}")
        manifest["edits"].append({
            "address": hex(address), "before": nop_before.hex(), "after": nop_after.hex(),
            "reason": "install alt1 endpoint: NOP alt0 filter",
        })
    manifest["edits"].sort(key=lambda edit: int(edit["address"], 16))
    ips_path = patch_dir / "atmosphere/exefs_patches/SysDVR-ISO" / (BUILD_ID + ".ips")
    ips_path.write_bytes(ips32([
        (int(edit["address"], 16), bytes.fromhex(edit["after"])) for edit in manifest["edits"]
    ]))
    manifest["patch_sha256"] = sha(ips_path)
    manifest.update(
        schema=layout["schema"],
        trace_layout=layout["trace_layout"],
        diagnostics_magic=layout["magic"],
        trace_fields=layout["fields"],
        injection_bytes=len(payload),
        injection_limit=684,
        injection_free=684 - len(payload),
        source_commit=SAFE_STREAM_COMMIT,
        hardware_verified=False,
        packaged=False,
        usb_accessed=False,
        sd_accessed=False,
    )
    (patch_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    header = out / "iso_runtime_payload.h"
    stream_header = out / "iso_runtime_stream_payload.h"
    runtime_header(manifest, header)
    stream_stub_header(payload, stream_header)

    result = {
        "schema": layout["schema"].replace("-1", "-build-1"),
        "payload_sha256": hashlib.sha256(payload).hexdigest(),
        "injection_bytes": len(payload),
        "injection_limit": 684,
        "injection_free": 684 - len(payload),
        "patch_sha256": sha(patch_dir / "atmosphere/exefs_patches/SysDVR-ISO" / (BUILD_ID + ".ips")),
        "source_commit": SAFE_STREAM_COMMIT,
        "stream_buffers": 640,
        "one_in_flight": True,
        "runtime_edits": len(manifest["edits"]),
        "defines": "-DISO_PROBE -DISO_PROBE_STREAM -DISO_RUNTIME_PATCH -DFILE_LOGGING "
        "-DISO_PROBE_ALT1 -DISO_PROBE_MPS=256 -DISO_PROBE_INTERVAL=4",
        "nsp": None,
        "hardware_verified": False,
        "packaged": False,
        "usb_accessed": False,
        "sd_accessed": False,
    }
    if not args.skip_nsp:
        src = out / "build-source"
        src.mkdir()
        prepare_source(src, header, stream_header)
        nsp = build_nsp(out, src, out / "outputs")
        result["nsp"] = nsp.name
        result["nsp_sha256"] = sha(nsp)
    (out / "result.json").write_text(json.dumps(result, indent=2) + "\n")
    (out / "SHA256SUMS").write_text(
        "".join(
            sha(p) + "  " + p.relative_to(out).as_posix() + "\n"
            for p in sorted(out.rglob("*"))
            if p.is_file() and p.name != "SHA256SUMS"
        )
    )
    print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
