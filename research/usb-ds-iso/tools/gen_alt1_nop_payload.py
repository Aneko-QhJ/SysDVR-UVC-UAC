#!/usr/bin/env python3
"""Generate the runtime NOP payload header for the ALT1 endpoint-install test.

Build with:
  make -B OUTPUT_DIR=/tmp/alt1-runtime \
    DEFINES="-DALT1_PROBE -DISO_PROBE -DISO_RUNTIME_PATCH -DFILE_LOGGING"

The generated header is not tracked; run this script first. The patch NOPs the
eight alt0-only endpoint filters in usb:ds FUN_000295d0 (Build-ID AD8D...).
"""
import argparse
from pathlib import Path

BUILD_ID = bytes.fromhex(
    "AD8D36F2029822A4C498F055ADBDAA789EB913C6000000000000000000000000"
)
ADDRS = [0x29694, 0x29AD4, 0x29BA4, 0x29C88, 0x29D54, 0x29E38, 0x29F04, 0x29FE8]
BEFORE = bytes.fromhex("09ffff35")  # cbnz w9, loop
AFTER = bytes.fromhex("1f2003d5")   # nop
DEFAULT_OUT = Path(__file__).resolve().parents[3] / "source/uvc/iso_runtime_payload.h"


def build_text():
    lines = [
        "/* Generated by tools/gen_alt1_nop_payload.py; not tracked. */",
        "static const unsigned char isoRuntimeBuildId[32]={"
        + ",".join(str(b) for b in BUILD_ID) + "};",
    ]
    for i, _ in enumerate(ADDRS):
        lines.append(
            f"static const unsigned char isoRuntime_{i}_before[]={{"
            + ",".join(str(b) for b in BEFORE) + "};"
        )
        lines.append(
            f"static const unsigned char isoRuntime_{i}_after[]={{"
            + ",".join(str(b) for b in AFTER) + "};"
        )
    edits = ",".join(
        f"{{0x{a:x},4,isoRuntime_{i}_before,isoRuntime_{i}_after}}"
        for i, a in enumerate(ADDRS)
    )
    lines.append("static const IsoRuntimeEdit isoRuntimeEdits[]={" + edits + "};")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(build_text())
    print(f"wrote {args.output} ({len(ADDRS)} edits)")


if __name__ == "__main__":
    main()
