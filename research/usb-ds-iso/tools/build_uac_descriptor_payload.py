#!/usr/bin/env python3
"""Build the descriptor-only runtime payload for the UAC configuration fix.

The payload carries exactly the 18 configuration-length edits that widen the
usb:ds u8 length/offset stores and loads to u16.  It deliberately excludes the
four A23 ISO entries (cave injection and event/report hooks) so a UAC build can
apply the descriptor fix without pulling in the ISO producer.

Inputs are the extracted usb ELF and the already-established edit list from
tools/build_patch.py.  The script validates every "before" word against the ELF
before writing anything; no USB, SD or hardware access.
"""
import argparse
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_ELF = ROOT / "private/module/usb.elf"
DEFAULT_OUT = ROOT / "private/analysis/UAC-descriptor-patch-20261029/uac_descriptor_payload.h"
DEFAULT_MANIFEST = ROOT / "private/analysis/UAC-descriptor-patch-20261029/manifest.json"

USB_ELF_SHA256 = "10b280d446daf116f139dbc8301968e899587a6b7dab229d5e4af6214078da29"
USB_ELF_SIZE = 857672
USB_BUILD_ID = bytes.fromhex(
    "AD8D36F2029822A4C498F055ADBDAA789EB913C6000000000000000000000000"
)
ISO_ONLY_ADDRESSES = {0x68D54, 0x30364, 0x30898, 0x2CBE0}

# address -> (before, after); from the established A23 descriptor fix.
EDITS = [
    (0x2BF1C, 0x391152D5, 0x7908AAD5),
    (0x2BF94, 0x391152D5, 0x7908AAD5),
    (0x2C028, 0x391152D5, 0x7908AAD5),
    (0x2C0A0, 0x391152D5, 0x7908AAD5),
    (0x2C11C, 0x391152D5, 0x7908AAD5),
    (0x2BF8C, 0x395152C8, 0x7948AAC8),
    (0x2C020, 0x395152C8, 0x7948AAC8),
    (0x2C098, 0x395152C8, 0x7948AAC8),
    (0x2C114, 0x395152C8, 0x7948AAC8),
    (0x2BFB8, 0x395152D5, 0x7948AAD5),
    (0x2C0B0, 0x395152D5, 0x7948AAD5),
    (0x2C138, 0x395152D5, 0x7948AAD5),
    (0x2C148, 0x395152D5, 0x7948AAD5),
    (0x2BFEC, 0x8B3502E0, 0x8B3542E0),
    (0x2C064, 0x8B3502E0, 0x8B3542E0),
    (0x2C0E0, 0x8B3502E0, 0x8B3542E0),
    (0x2C158, 0x12001EA8, 0x2A1503E8),
    (0x2BDB8, 0x38686A68, 0x78686A68),
]


def sha256(data):
    return hashlib.sha256(data).hexdigest()


def load_elf_sections(path):
    data = Path(path).read_bytes()
    if len(data) < 64 or data[:4] != b"\x7fELF":
        raise ValueError("not an ELF file")
    e_shoff = struct.unpack_from("<Q", data, 40)[0]
    e_shentsize = struct.unpack_from("<H", data, 58)[0]
    e_shnum = struct.unpack_from("<H", data, 60)[0]
    sections = {}
    for i in range(e_shnum):
        off = e_shoff + i * e_shentsize
        name_off, sh_type, _flags, sh_addr, sh_offset, sh_size = struct.unpack_from(
            "<IIQQQQ", data, off
        )
        sections[i] = {
            "name_off": name_off,
            "type": sh_type,
            "addr": sh_addr,
            "offset": sh_offset,
            "size": sh_size,
        }
    return data, sections


def validate(data, sections):
    if len(data) != USB_ELF_SIZE:
        raise ValueError(f"usb ELF size mismatch: {len(data)}")
    if sha256(data) != USB_ELF_SHA256:
        raise ValueError("usb ELF SHA256 mismatch; refusing an unknown input")
    for address, before, after in EDITS:
        if address in ISO_ONLY_ADDRESSES:
            raise ValueError("descriptor payload must not include ISO edits")
        start = None
        for sec in sections.values():
            if sec["type"] != 8 and sec["addr"] <= address < sec["addr"] + sec["size"]:
                start = sec["offset"] + address - sec["addr"]
                break
        if start is None:
            raise ValueError(f"{address:#x} outside mapped sections")
        actual = struct.unpack_from("<I", data, start)[0]
        if actual != before:
            raise ValueError(
                f"{address:#x}: expected {before:#08x}, found {actual:#08x}"
            )


def render():
    lines = [
        "/* Generated by tools/build_uac_descriptor_payload.py; not tracked. */",
        "static const unsigned char uacRuntimeBuildId[32]={"
        + ",".join(str(b) for b in USB_BUILD_ID)
        + "};",
    ]
    for i, (address, before, after) in enumerate(EDITS):
        lines.append(
            f"static const unsigned char uacRuntime_{i}_before[]={{"
            + ",".join(str(b) for b in struct.pack("<I", before))
            + "};"
        )
        lines.append(
            f"static const unsigned char uacRuntime_{i}_after[]={{"
            + ",".join(str(b) for b in struct.pack("<I", after))
            + "};"
        )
    records = []
    for i, (address, _before, _after) in enumerate(EDITS):
        records.append(
            f"{{0x{address:x},4,uacRuntime_{i}_before,uacRuntime_{i}_after}}"
        )
    lines.append("static const IsoRuntimeEdit uacRuntimeEdits[]={" + ",".join(records) + "};")
    return "\n".join(lines) + "\n"


def manifest(header, elf_path):
    return {
        "schema": "UAC-descriptor-payload-1",
        "elf": str(elf_path),
        "elf_sha256": USB_ELF_SHA256,
        "elf_size": USB_ELF_SIZE,
        "build_id": USB_BUILD_ID.hex().upper(),
        "edits": [
            {
                "address": f"0x{address:x}",
                "before": f"{before:08x}",
                "after": f"{after:08x}",
            }
            for address, before, after in EDITS
        ],
        "edit_count": len(EDITS),
        "includes_iso_edits": False,
        "header_sha256": sha256(header.encode()),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--elf", type=Path, default=DEFAULT_ELF)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--manifest", type=Path, default=DEFAULT_MANIFEST)
    parser.add_argument("--check", action="store_true", help="verify existing outputs")
    args = parser.parse_args()

    data = args.elf.read_bytes()
    _raw, sections = load_elf_sections(args.elf)
    validate(data, sections)
    header = render()
    doc = manifest(header, args.elf)

    if args.check:
        current = args.out.read_text()
        if current != header:
            raise SystemExit("payload header differs from generator output")
        if json.loads(args.manifest.read_text()) != doc:
            raise SystemExit("manifest differs from generator output")
        print(f"ok: {len(EDITS)} edits, {args.out}")
        return

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(header)
    args.manifest.write_text(json.dumps(doc, indent=2) + "\n")
    print(f"wrote {args.out} ({len(EDITS)} edits)")
    print(f"wrote {args.manifest}")


if __name__ == "__main__":
    main()
